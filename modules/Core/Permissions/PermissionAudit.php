<?php

declare(strict_types=1);

namespace Modules\Core\Permissions;

use CodeIgniter\Router\RouteCollection;
use Config\Services;
use Modules\Core\Crud\CrudAuditor;
use Modules\Core\Modules\ModuleDiscovery;

/**
 * What `php spark permissions:check` reports, so the manifests, the catalogue, the grants,
 * Shield's matrix and the route filters cannot drift apart:
 *
 * - errors: invalid manifests or duplicate permission names; generated permissions missing from
 *   the stored catalogue (run `modules:sync`); Shield's matrix out of date; route problems
 *   (`RouteSecurityAuditor`, with the generated catalogue); kpcrudy CRUDs not made with
 *   `CrudFactory` or asking about undeclared operations (`CrudAuditor`).
 * - warnings: stored permissions no manifest generates (`modules:sync --prune`); grants naming
 *   unknown permissions; atomic grants without the permissions they imply.
 *
 * Diagnostics are written in English (developer output, like exception messages).
 */
final class PermissionAudit
{
    public function __construct(
        private readonly ?ModuleDiscovery $discovery = null,
        private readonly ?RouteCollection $routes = null,
        private readonly PermissionCatalogue $catalogue = new PermissionCatalogue(),
    ) {
    }

    /**
     * @return array{errors: list<string>, warnings: list<string>, permissions: int, routes: int}
     */
    public function run(): array
    {
        $errors    = [];
        $warnings  = [];
        $manifests = [];

        foreach (($this->discovery ?? new ModuleDiscovery())->discover() as $name => $module) {
            if ($module->isValid() && $module->manifest !== null) {
                $manifests[$name] = $module->manifest;
            } else {
                $errors = [...$errors, ...$module->errors];
            }
        }

        $builder   = new CatalogueBuilder();
        $generated = $builder->build($manifests);
        $errors    = [...$errors, ...$builder->errors()];
        $names     = array_keys($generated);

        if (db_connect()->tableExists('permissions')) {
            $stored = $this->catalogue->stored();

            foreach (array_diff($names, array_keys($stored)) as $missing) {
                $errors[] = "{$missing} is generated by a manifest but not stored: run `php spark modules:sync`.";
            }

            foreach (array_diff(array_keys($stored), $names) as $stale) {
                $warnings[] = "{$stale} is stored but no manifest generates it: `php spark modules:sync --prune` removes it.";
            }

            $operations = ImpliedPermissions::operationsOf($stored);

            foreach ($this->catalogue->allGrants() as $group => $grants) {
                foreach ($grants as $grant) {
                    if (! ShieldMatrix::effective($grant, array_keys($stored))) {
                        $warnings[] = "The group {$group} is granted {$grant}, which names no permission of the catalogue.";
                    }
                }

                $missing = array_diff(ImpliedPermissions::complete($grants, $operations), $grants);

                if ($missing !== []) {
                    $warnings[] = "The group {$group} lacks permissions implied by its grants: " . implode(', ', $missing) . '.';
                }
            }

            if (db_connect()->tableExists('settings') && ! (new ShieldMatrix($this->catalogue))->inSync()) {
                $errors[] = "Shield's AuthGroups permissions and matrix do not match the catalogue and group_permissions: run `php spark modules:sync`.";
            }
        } else {
            $errors[] = 'The permission tables do not exist: run `php spark modules:sync`.';
        }

        $routes = $this->routes ?? Services::routes(false)->loadRoutes(); // a fresh collection: the shared one keeps request state
        $errors = [...$errors, ...(new RouteSecurityAuditor())->audit($routes, $names)];

        if (db_connect()->tableExists('permissions')) {
            $errors = [...$errors, ...(new CrudAuditor($this->catalogue))->audit($routes)];
        }

        return [
            'errors'      => $errors,
            'warnings'    => $warnings,
            'permissions' => count($names),
            'routes'      => count((new RouteSecurityAuditor())->routes($routes)),
        ];
    }
}
