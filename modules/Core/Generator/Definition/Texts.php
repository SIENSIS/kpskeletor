<?php

declare(strict_types=1);

namespace Modules\Core\Generator\Definition;

/**
 * A text of the generated module in the three shipped languages (`ca`, `es`, `en`). A missing
 * language takes the English text, then any given one, then the fallback (usually the
 * humanised name), so a definition may give only one of them.
 */
final class Texts
{
    /**
     * The shipped languages of the user interface: a generated module's language files are
     * complete in these three (`CLAUDE.md`, "Languages"). Not content languages (those come from
     * `Modules\Core\I18n\Locales`); the one place of the generator that names them
     * (`ContentLanguagesTest` allows this file).
     */
    public const LOCALES = ['ca', 'es', 'en'];

    /** Fixed texts the generator writes into every module's language files. */
    public const FIXED = [
        'allRecords'  => ['ca' => 'Tots els registres', 'es' => 'Todos los registros', 'en' => 'Every record'],
        'createdBy'   => ['ca' => 'Creat per', 'es' => 'Creado por', 'en' => 'Created by'],
        'createdAt'   => ['ca' => 'Creat', 'es' => 'Creado', 'en' => 'Created'],
        'updatedAt'   => ['ca' => 'Modificat', 'es' => 'Modificado', 'en' => 'Updated'],
        'done'        => ['ca' => 'Fet.', 'es' => 'Hecho.', 'en' => 'Done.'],
        'generated'   => ['ca' => 'Generat pel generador de codi.', 'es' => 'Generado por el generador de código.', 'en' => 'Generated by the code generator.'],
    ];

    /**
     * A fixed text (`FIXED`) as Texts.
     */
    public static function fixed(string $key): self
    {
        return self::from(self::FIXED[$key], '');
    }

    /** The English text (doc comments of generated code). */
    public function english(): string
    {
        return $this->get('en');
    }

    /** The text of the first shipped language (demo values). */
    public function first(): string
    {
        return $this->get(self::LOCALES[0]);
    }

    /**
     * The same value for each shipped language.
     *
     * @return array<string, mixed>
     */
    public static function each(mixed $value): array
    {
        return array_fill_keys(self::LOCALES, $value);
    }

    /**
     * @param array<string, string> $texts locale => text
     */
    private function __construct(public readonly array $texts)
    {
    }

    public static function from(mixed $value, string $fallback): self
    {
        $given = [];

        if (is_string($value) && trim($value) !== '') {
            $given = array_fill_keys(self::LOCALES, trim($value));
        } elseif (is_array($value)) {
            foreach (self::LOCALES as $locale) {
                if (is_string($value[$locale] ?? null) && trim($value[$locale]) !== '') {
                    $given[$locale] = trim($value[$locale]);
                }
            }
        }

        $default = $given['en'] ?? ($given === [] ? $fallback : reset($given));
        $texts   = [];

        foreach (self::LOCALES as $locale) {
            $texts[$locale] = $given[$locale] ?? $default;
        }

        return new self($texts);
    }

    public function get(string $locale): string
    {
        return $this->texts[$locale] ?? $this->texts['en'];
    }

    /**
     * @return array<string, string>
     */
    public function toArray(): array
    {
        return $this->texts;
    }

    /**
     * `book_title` → `Book title`.
     */
    public static function humanise(string $name): string
    {
        $text = trim((string) preg_replace('/[_\-\s]+/', ' ', $name));

        return $text === '' ? $name : ucfirst($text);
    }
}
