<?php

declare(strict_types=1);

namespace Modules\Core\Modules;

/**
 * Writes the generated `app/Config/ModuleNamespaces.php` (one PSR-4 namespace per module),
 * merged by `app/Config/Autoload.php`.
 */
final class NamespaceFile
{
    private readonly string $file;

    public function __construct(?string $file = null)
    {
        $this->file = $file ?? APPPATH . 'Config/ModuleNamespaces.php';
    }

    public function path(): string
    {
        return $this->file;
    }

    /**
     * Writes the file when its content changes.
     *
     * @param array<string, string> $folders module name => absolute path
     *
     * @return bool Whether the file was (re)written
     */
    public function write(array $folders): bool
    {
        $content = $this->render($folders);

        if (is_file($this->file) && file_get_contents($this->file) === $content) {
            return false;
        }

        $tmp = $this->file . '.' . bin2hex(random_bytes(4)) . '.tmp';

        if (file_put_contents($tmp, $content, LOCK_EX) === false || ! rename($tmp, $this->file)) {
            @unlink($tmp);

            throw new \RuntimeException(lang('Core.sync.namespacesNotWritable', [$this->file]));
        }

        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($this->file, true);
        }

        return true;
    }

    /**
     * @param array<string, string> $folders module name => absolute path
     */
    public function render(array $folders): string
    {
        ksort($folders);

        $modulesRoot = $this->normalise(ROOTPATH . 'modules') . '/';
        $configDir   = $this->normalise(dirname($this->file));
        $relative    = $configDir === $this->normalise(APPPATH . 'Config');
        $lines       = [];

        foreach ($folders as $name => $path) {
            $path = $this->normalise($path);

            $target = $relative && str_starts_with($path . '/', $modulesRoot)
                ? "__DIR__ . '/../../modules/" . substr($path, strlen($modulesRoot)) . "'"
                : var_export($path, true);

            $lines[] = "    'Modules\\{$name}' => {$target},";
        }

        return "<?php\n\n"
            . "declare(strict_types=1);\n\n"
            . "/*\n"
            . " * GENERATED by `php spark modules:sync` and `php spark make:module`: do not edit by hand.\n"
            . " *\n"
            . " * One PSR-4 namespace per module, merged by app/Config/Autoload.php so that CodeIgniter's\n"
            . " * discovery finds each module's Config/Routes.php, Config/Registrar.php, commands and\n"
            . " * language files.\n"
            . " */\n\n"
            . "return [\n"
            . implode("\n", $lines) . ($lines === [] ? '' : "\n")
            . "];\n";
    }

    private function normalise(string $path): string
    {
        $real = realpath($path);

        return rtrim(str_replace('\\', '/', $real !== false ? $real : $path), '/');
    }
}
