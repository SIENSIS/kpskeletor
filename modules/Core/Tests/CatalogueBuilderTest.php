<?php

declare(strict_types=1);

namespace Modules\Core\Tests;

use CodeIgniter\Test\CIUnitTestCase;
use Modules\Core\Config\Module as CoreModule;
use Modules\Core\Config\ModuleManifest;
use Modules\Core\Permissions\CatalogueBuilder;
use Modules\Core\Permissions\DefaultGrants;

/**
 * The permission catalogue is generated from the manifests; default grants get their implied
 * permissions.
 *
 * @internal
 */
final class CatalogueBuilderTest extends CIUnitTestCase
{
    protected function setUp(): void
    {
        parent::setUp();
        service('language')->setLocale('en');
    }

    private function news(): ModuleManifest
    {
        return new class () extends ModuleManifest {
            public string $name      = 'News';
            public array $resources  = [
                'posts' => [
                    'label'  => 'News.res.posts',
                    'type'   => 'crud',
                    'except' => ['import'],
                    'extra'  => ['publish' => 'News.perm.publish'],
                ],
                'categories' => [
                    'label'  => 'News.res.categories',
                    'type'   => 'crud',
                    'except' => ['trash', 'restore', 'purge', 'import', 'list'],
                ],
                'stats' => ['label' => 'News.res.stats', 'type' => 'page', 'extra' => ['export' => 'News.perm.exportStats']],
            ];
            public array $settings = ['perPage' => ['type' => 'int', 'default' => 20, 'label' => 'News.settings.perPage']];
            public array $defaultGrants = [
                'admin'  => ['news-posts.*', 'news-stats.view'],
                'editor' => ['news-posts.edit', 'news-posts.restore', 'news-categories.edit', 'news-posts.publish'],
            ];
        };
    }

    public function testCrudPageExtraAndSettingsPermissions(): void
    {
        $catalogue = (new CatalogueBuilder())->build(['News' => $this->news()]);

        $this->assertSame([
            'news-posts.list', 'news-posts.show', 'news-posts.add', 'news-posts.edit', 'news-posts.delete',
            'news-posts.export', 'news-posts.trash', 'news-posts.restore', 'news-posts.purge', 'news-posts.publish',
            'news-categories.show', 'news-categories.add', 'news-categories.edit', 'news-categories.delete', 'news-categories.export',
            'news-stats.view', 'news-stats.export',
            'settings.news',
        ], array_keys($catalogue));

        $this->assertSame(
            ['module' => 'News', 'resource' => 'posts', 'operation' => 'publish', 'name' => 'news-posts.publish', 'description' => 'News.perm.publish'],
            $catalogue['news-posts.publish'],
        );
        $this->assertSame('Core.perm.edit', $catalogue['news-posts.edit']['description']);
        $this->assertSame(['News', 'settings', 'news'], [$catalogue['settings.news']['module'], $catalogue['settings.news']['resource'], $catalogue['settings.news']['operation']]);
    }

    public function testNameOverrideIsHonoured(): void
    {
        $catalogue = (new CatalogueBuilder())->build(['Core' => new CoreModule()]);

        $this->assertSame(
            ['modules.list', 'modules.toggle', 'modules.sync', 'modules.upload', 'modules.uninstall', 'modules.demo'],
            array_keys($catalogue),
        );
        $this->assertSame('modules', $catalogue['modules.demo']['resource']);
    }

    public function testDuplicatePermissionsAreRefused(): void
    {
        $files = new class () extends ModuleManifest {
            public string $name     = 'Files';
            public array $resources = ['library' => ['label' => 'Files.res', 'type' => 'page', 'name' => 'news-stats']];
        };

        $builder   = new CatalogueBuilder();
        $catalogue = $builder->build(['News' => $this->news(), 'Files' => $files]);

        $this->assertSame('News', $catalogue['news-stats.view']['module'], 'the first module keeps the name');
        $this->assertSame(
            ["Files: \$resources['library'] generates the permission \"news-stats.view\", already generated by the module News"],
            $builder->errors(),
        );
    }

    public function testDefaultGrantsGetTheirImpliedPermissions(): void
    {
        $grants = (new DefaultGrants())->expand($this->news());

        $this->assertSame(['news-posts.*', 'news-stats.view'], $grants['admin'], 'wildcards are kept as they are');
        $this->assertSame([
            'news-categories.edit', 'news-categories.show', // "list" is not in the categories catalogue
            'news-posts.edit', 'news-posts.list', 'news-posts.publish', 'news-posts.restore', 'news-posts.show', 'news-posts.trash',
        ], $grants['editor']);
    }
}
