<?php

declare(strict_types=1);

namespace Modules\Core\Tests;

use CodeIgniter\Test\StreamFilterTrait;
use Modules\Core\Permissions\PermissionAudit;

/**
 * `permissions:list` and `permissions:check` (PermissionAudit).
 *
 * @internal
 */
final class PermissionsCommandsTest extends RbacTestCase
{
    use StreamFilterTrait;

    public function testCheckPassesOnASyncedInstallation(): void
    {
        $result = (new PermissionAudit())->run();

        $this->assertSame([], $result['errors']);
        $this->assertSame(32, $result['permissions']);
        $this->assertGreaterThan(0, $result['routes']);
        $this->assertContains('news-posts.edit is stored but no manifest generates it: `php spark modules:sync --prune` removes it.', $result['warnings']);

        command('permissions:check');
        $this->assertStringContainsString('Permissions OK: 32 permission(s)', $this->getStreamFilterBuffer());
    }

    public function testCheckReportsAStaleMatrixUnknownGrantsAndIncompleteSets(): void
    {
        $db = db_connect();
        $db->table('group_permissions')->insertBatch([
            ['group' => 'user', 'permission' => 'news-posts.edit', 'created_at' => '2026-11-05 10:00:00'],
            ['group' => 'user', 'permission' => 'gone.list', 'created_at' => '2026-11-05 10:00:00'],
        ]);

        $result = (new PermissionAudit())->run();

        $this->assertStringContainsString("Shield's AuthGroups permissions and matrix do not match", implode("\n", $result['errors']));
        $this->assertContains('The group user is granted gone.list, which names no permission of the catalogue.', $result['warnings']);
        $this->assertContains('The group user lacks permissions implied by its grants: news-posts.list, news-posts.show.', $result['warnings']);
    }

    public function testCheckReportsPermissionsMissingFromTheStoredCatalogue(): void
    {
        db_connect()->table('permissions')->where('name', 'modules.sync')->delete();

        $this->assertContains(
            'modules.sync is generated by a manifest but not stored: run `php spark modules:sync`.',
            (new PermissionAudit())->run()['errors'],
        );
    }

    public function testListShowsTheGroupsThatHoldEachPermission(): void
    {
        command('permissions:list --module=Core');
        $output = $this->getStreamFilterBuffer();

        $this->assertMatchesRegularExpression('/modules\.list\s*\|\s*Core\s*\|.*\|\s*superadmin, admin\s*\|/', $output);
        $this->assertMatchesRegularExpression('/modules\.upload\s*\|\s*Core\s*\|.*\|\s*superadmin\s*\|/', $output);
        $this->assertStringNotContainsString('auth-profile', $output);

        $this->resetStreamFilterBuffer();
        command('permissions:list --group=user');
        $this->assertStringContainsString('auth-sessions.revoke', $this->getStreamFilterBuffer());
        $this->assertStringNotContainsString('modules.list', $this->getStreamFilterBuffer());
    }
}
