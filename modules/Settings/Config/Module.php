<?php

declare(strict_types=1);

namespace Modules\Settings\Config;

use Modules\Core\Config\ModuleManifest;
use Modules\Core\Modules\ManifestValidator;

/**
 * Manifest of the Settings module: the settings screens generated from the manifests'
 * `$settings` (docs/specification.md, "Configuration and settings" and "Modules" › "Settings";
 * docs/settings.md).
 *
 * One resource named `settings` (single-resource module, D-00-18) with only two operations:
 * - `settings.update` opens the screens (every tab, read-only without the tab's permission) and
 *   runs the actions "send a test email" and "clear caches";
 * - `settings.security` opens and saves Settings › Security (with a re-authentication) and runs
 *   "publish assets".
 * Changing a module's tab needs `settings.<module>`, generated by the Core for every module that
 * declares settings; the theme tab needs `settings.core`. Superadmins bypass every check.
 */
final class Module extends ModuleManifest
{
    public string $name    = 'Settings';
    public string $version = '0.1.0';
    public string $icon    = 'bi bi-gear';
    public array $requires = ['Core' => '^0.1', 'Auth' => '^0.2'];

    public array $resources = [
        'settings' => [
            'label'  => 'Settings.res.settings',
            'type'   => 'crud',
            'name'   => 'settings',
            'except' => ManifestValidator::CRUD_OPERATIONS,
            'extra'  => [
                'update'   => 'Settings.perm.update',
                'security' => 'Settings.perm.security',
            ],
        ],
    ];

    /** Administrators get every tab, Settings › Security included (`settings.*`). */
    public array $defaultGrants = [
        'admin' => ['settings.*'],
    ];

    public array $menu = [
        ['route' => 'settings', 'permission' => 'settings.update', 'label' => 'Settings.menu.settings', 'icon' => 'bi bi-gear', 'order' => 70, 'zone' => 'settings'],
        ['route' => 'settings-security', 'permission' => 'settings.security', 'label' => 'Settings.menu.security', 'icon' => 'bi bi-shield-lock', 'order' => 71, 'zone' => 'settings'],
    ];
}
