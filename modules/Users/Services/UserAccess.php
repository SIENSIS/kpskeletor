<?php

declare(strict_types=1);

namespace Modules\Users\Services;

use CodeIgniter\Shield\Entities\User;
use Config\Database;
use Modules\Auth\Exceptions\GroupRuleException;
use Modules\Auth\Services\GroupRules;
use Modules\Core\Groups\GroupRegistry;
use Modules\Core\Permissions\EscalationException;
use Modules\Core\Permissions\EscalationGuard;
use Modules\Core\Permissions\GrantManager;
use Modules\Core\Permissions\PermissionCatalogue;
use Throwable;

/**
 * A user's groups and individual permissions (the "Groups and permissions" screen), changed
 * only through Auth's `GroupRules` and the Core's `GrantManager`, so every escalation rule
 * applies (nobody changes their own access, only superadmins touch superadmins, a user can only
 * give what they hold, the last superadmin keeps the group). Saved in one transaction; the user's
 * sessions are regenerated by those services.
 */
final class UserAccess
{
    public function __construct(
        private readonly PermissionCatalogue $catalogue = new PermissionCatalogue(),
        private readonly GroupRules $rules = new GroupRules(),
    ) {
    }

    /**
     * The groups (name => title) and whether `$actor` may add or remove each one for `$target`.
     *
     * @return array<string, array{title: string, member: bool, editable: bool}>
     */
    public function groups(User $actor, User $target): array
    {
        $result = [];

        foreach ((new GroupRegistry($this->catalogue))->all() as $name => $group) {
            $member        = $target->inGroup($name);
            $result[$name] = [
                'title'    => $group['title'],
                'member'   => $member,
                'editable' => $member ? $this->rules->canRemove($actor, $target, $name) : $this->rules->canAssign($actor, $target, $name),
            ];
        }

        return $result;
    }

    /**
     * Atomic permissions of the enabled modules the screen offers, with whether the target holds
     * them individually and whether the actor may grant them.
     *
     * @return array<string, array<string, array{label: string, operations: array<string, array{name: string, label: string, held: bool, editable: bool}>}>>
     */
    public function permissions(User $actor, User $target): array
    {
        $guard    = new EscalationGuard($this->catalogue);
        $own      = array_flip(array_map('strtolower', $target->getPermissions() ?? []));
        $canTouch = $guard->canChangeUserPermissions($actor, $target);
        $blocks   = (new PermissionMatrix($this->catalogue))->blocks();

        foreach ($blocks as $module => $resources) {
            foreach ($resources as $prefix => $resource) {
                foreach ($resource['operations'] as $operation => $entry) {
                    $held = isset($own[$entry['name']]);

                    $blocks[$module][$prefix]['operations'][$operation] += [
                        'held'     => $held,
                        'editable' => $canTouch && ($held || $guard->canGrant($actor, [$entry['name']])),
                    ];
                }
            }
        }

        /** @var array<string, array<string, array{label: string, operations: array<string, array{name: string, label: string, held: bool, editable: bool}>}>> $blocks */
        return $blocks;
    }

    /**
     * Saves the posted groups and individual permissions.
     *
     * @param list<string> $groups      Groups the user must be in
     * @param list<string> $permissions Individual permissions the user must hold
     *
     * @return bool Whether something changed
     *
     * @throws EscalationException|GroupRuleException (nothing is saved)
     */
    public function save(User $actor, User $target, array $groups, array $permissions): bool
    {
        $current     = $target->getGroups() ?? [];
        $known       = array_keys((new GroupRegistry($this->catalogue))->all());
        $groups      = array_values(array_intersect(array_unique($groups), $known));
        $toAdd       = array_values(array_diff($groups, $current));
        $toRemove    = array_values(array_diff($current, $groups));
        $own         = array_map('strtolower', $target->getPermissions() ?? []);
        $permissions = array_values(array_unique(array_map(static fn (string $p): string => strtolower(trim($p)), $permissions)));
        $grant       = array_values(array_diff($permissions, $own));
        // Only what the screen shows can be revoked (permissions of disabled modules are kept).
        $shown       = (new PermissionMatrix($this->catalogue))->editableNames();
        $revoke      = array_values(array_intersect(array_diff($own, $permissions), $shown));

        if ($toAdd === [] && $toRemove === [] && $grant === [] && $revoke === []) {
            return false;
        }

        $db = Database::connect();
        $db->transException(true)->transStart();

        try {
            foreach ($toAdd as $group) {
                $this->rules->assign($actor, $target, $group);
            }

            foreach ($toRemove as $group) {
                $this->rules->remove($actor, $target, $group);
            }

            $manager = new GrantManager($this->catalogue);

            if ($grant !== []) {
                $manager->grantToUser($actor, $target, $grant);
            }

            if ($revoke !== []) {
                $manager->revokeFromUser($actor, $target, $revoke);
            }

            $db->transComplete();
        } catch (Throwable $e) {
            $db->transRollback();

            throw $e;
        }

        return true;
    }
}
